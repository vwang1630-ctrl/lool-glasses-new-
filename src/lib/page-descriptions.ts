export type PageDescKey = keyof typeof D;

/** Translator for head(): the URL's lang if supported, else en. Lets a page
 * reuse its own on-page (design-source) copy from the i18n dictionary as its
 * description instead of a separate text. */
export function headTranslator(lang: string | undefined) {
  const l = (SUPPORTED_LANG_CODES as readonly string[]).includes(lang ?? "")
    ? (lang as Lang)
    : "en";
  return getTranslator(l);
}

function pick(t: Texts, lang: string | undefined): string {
  return (lang && (t as Record<string, string>)[lang]) || t.en;
}

/** Localized meta description for a page (falls back to en). */
export function pageDesc(key: PageDescKey, lang: string | undefined): string {
  return pick(D[key], lang);
}

/** Localized og:/twitter:description — the short variant if the page has one. */
export function pageOgDesc(key: PageDescKey, lang: string | undefined): string {
  const og = (O as Partial<Record<PageDescKey, Texts>>)[key];
  return og ? pick(og, lang) : pageDesc(key, lang);
}
